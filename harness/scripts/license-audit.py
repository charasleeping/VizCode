"""Deterministic evidence inventory. Refresh is explicit; packaging only checks."""
import argparse,hashlib,json,re,sys,fnmatch,zipfile,xml.etree.ElementTree as ET
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
PRIVATE=Path('.private/maintainer-audit')
def digest(path):return hashlib.sha256(path.read_bytes()).hexdigest()
def snapshot(root,patterns):
 out={}
 for pattern in patterns:
  for p in sorted(root.glob(pattern)):
   if p.is_file() and not any(x in p.parts for x in ['__pycache__','.git','node_modules']):out[p.relative_to(root).as_posix()]=digest(p)
 return out
def module_packages(root):
 result=set();files=list((root/'plugin/vizcode/execution-assets/license-modules').glob('*.json'))
 for file in files:result.update(json.loads(file.read_text())['packages'])
 return result,files

def refresh(root):
 policy=json.loads((root/PRIVATE/'licensing/components.json').read_text());entries=[]
 bundled,modulefiles=module_packages(root);bundled.update(policy.get('copied_packages',[]))
 for item in policy['components']:
  entry=dict(item);entry['files']=snapshot(root,item['patterns']);entry['evidence']={p:digest(root/p) for p in item.get('license_files',[]) if (root/p).is_file()};entries.append(entry)
 for lockname in ['plugin/vizcode/frontend/package-lock.json','harness/package-lock.json']:
  lock=root/lockname;packages=json.loads(lock.read_text())['packages'];base=lock.parent
  for key,v in sorted(packages.items()):
   if not key:continue
   folder=base/key;name=key.split('node_modules/')[-1];version=v.get('version','unknown');evidence={}
   for p in sorted(folder.glob('*')):
    if p.is_file() and re.match(r'^(licen[cs]e|copying|notice)([.\-_]|$)',p.name,re.I):
     target=root/'plugin/vizcode/licenses/npm'/(re.sub('[^a-zA-Z0-9._-]','_',name)+'-'+version+'-'+p.name)
     target.write_bytes(p.read_bytes());evidence[target.relative_to(root).as_posix()]=digest(target)
   for extra in policy.get('license_overrides',{}).get(name,[]):
    evidence[extra]=digest(root/extra)
   shipped=lockname.startswith('plugin/') and key in bundled
   entries.append({'id':('frontend:' if lockname.startswith('plugin/') else 'test:')+key,'version':version,'license':v.get('license','UNKNOWN'),'origin':v.get('resolved',''),'integrity':v.get('integrity',''),'status':'verified' if evidence and v.get('license') else 'incomplete-notices','distribution':'generated runtime modules' if shipped else 'not redistributed as a package; build/test dependency','shipped':shipped,'evidence':evidence,'copyright':'See retained version-specific license text','modifications':'No package-source edits; webpack transformations where bundled','source_access':v.get('resolved',''),'files':{}})
 inventory={'schema':1,'components':entries,'policy_sha256':digest(root/PRIVATE/'licensing/components.json'),'retrieval_sha256':digest(root/PRIVATE/'licensing/retrieved-evidence.json'),'locks':{p:digest(root/p) for p in ['plugin/vizcode/frontend/package-lock.json','harness/package-lock.json']},'module_manifests':{p.relative_to(root).as_posix():digest(p) for p in modulefiles},'artifacts':snapshot(root,['plugin/vizcode/assets/*','plugin/vizcode/execution-assets/**/*']),'publication_policy':'Block new releases until every shipped entry is verified; leave existing releases untouched.'}
 (root/PRIVATE/'licensing/inventory.json').write_text(json.dumps(inventory,indent=2,sort_keys=True)+'\n')
 lines=['# Dependency licensing inventory','', 'Generated by `python3 harness/scripts/license-audit.py refresh` after a reviewed build.','', 'Copyright for original VizCode contributions: Pui Chin Li (2026). Upstream copyrights remain with their owners.','', '## Publication blockers','']
 blockers=[e for e in entries if e.get('shipped') and e['status']!='verified']
 for e in blockers:lines.append('- **'+e['id']+'** — '+e['status']+': '+e.get('action','Obtain complete version-specific license and source evidence.'))
 lines+=['','## Inventory','', '| Component | Version | License | Distribution | Status |','| --- | --- | --- | --- | --- |']
 for e in entries:lines.append('| '+ ' | '.join(str(e.get(k,'—')).replace('|',' / ') for k in ['id','version','license','distribution','status'])+' |')
 lines+=['','Full file hashes, copyright evidence, modifications and source URLs are in [the machine-readable inventory](../licensing/inventory.json).','', 'Metadata alone is not permission. Unresolved entries require historical-source evidence or a written grant covering the actual modifications and redistribution. No maintainer contact is authorized automatically.','']
 (root/PRIVATE/'docs/LICENSING-INVENTORY.md').write_text('\n'.join(lines));print(f'Inventoried {len(entries)} components; {len(blockers)} shipped blockers.')
 # Moodle's registry lists code in the plugin itself, not backend-only runtimes.
 widget=json.loads((root/'plugin/vizcode/execution-assets/license-modules/widget.js.json').read_text())
 libraries=ET.Element('libraries')
 def library(name,version,license):
  item=ET.SubElement(libraries,'library')
  for tag,value in [('location','assets/widget.js'),('name',name),('version',version),('license',license)]:ET.SubElement(item,tag).text=value
 library('OPT_Mentor / Python Tutor visualizer (see third-party notices)',policy['components'][0]['version'],'See retained component notices')
 for name in ['jQuery','jQuery UI and assets','jsPlumb','jQuery BBQ','jQuery doTimeout']:
  e=next(e for e in entries if e['id']==name);library(name,e['version'],e['license'])
 library('jQuery Color (embedded in jQuery UI)','2.1.2','MIT')
 for e in entries:
  if e['id'].startswith('frontend:') and e['id'].split(':',1)[1] in widget['packages']:
   library(e['id'].split('node_modules/',1)[1],e['version'],e['license'])
 ET.indent(libraries,space='  ')
 (root/'plugin/vizcode/thirdpartylibs.xml').write_text('<?xml version="1.0" encoding="UTF-8"?>\n'+ET.tostring(libraries,encoding='unicode')+'\n')
 inventory['registry_sha256']=digest(root/'plugin/vizcode/thirdpartylibs.xml')
 (root/PRIVATE/'licensing/inventory.json').write_text(json.dumps(inventory,indent=2,sort_keys=True)+'\n')

def validate(root,inventory):
 errors=[]
 for path,key in [((PRIVATE/'licensing/components.json').as_posix(),'policy_sha256'),((PRIVATE/'licensing/retrieved-evidence.json').as_posix(),'retrieval_sha256')]:
  if key in inventory and digest(root/path)!=inventory[key]:errors.append('Changed audit policy/evidence: '+path)
 if 'registry_sha256' in inventory and digest(root/'plugin/vizcode/thirdpartylibs.xml')!=inventory['registry_sha256']:errors.append('Changed Moodle third-party registry')
 for field in ['locks','module_manifests','artifacts']:
  for name,expected in inventory.get(field,{}).items():
   path=root/name
   if not path.is_file() or digest(path)!=expected:errors.append('Changed/missing '+field+': '+name)
 packages,modulefiles=module_packages(root)
 if not modulefiles:errors.append('Missing actual webpack module manifests; build development assets first.')
 listed={e['id'].split(':',1)[1] for e in inventory['components'] if e['id'].startswith('frontend:')}
 for name in packages-listed:errors.append('Unlisted bundled dependency: '+name)
 covered=set().union(*(set(e.get('files',{})) for e in inventory['components']))
 policy=json.loads((root/PRIVATE/'licensing/components.json').read_text()) if (root/PRIVATE/'licensing/components.json').exists() else {}
 for manifest in modulefiles:
  for name in json.loads(manifest.read_text()).get('files',[]):
   if name not in covered and not any(fnmatch.fnmatch(name,p) for p in policy.get('first_party_patterns',[])):errors.append('Unclassified bundled source: '+name)
 actual=snapshot(root,['plugin/vizcode/assets/*','plugin/vizcode/execution-assets/**/*'])
 for name in actual.keys()-inventory.get('artifacts',{}).keys():errors.append('Unlisted distribution asset: '+name)
 for e in inventory['components']:
  if e.get('shipped') and e['status']!='verified':errors.append(e['id']+': '+e['status'])
  if e.get('shipped') and e['status']=='verified' and policy.get('compatible_licenses') is not None and e.get('license') not in policy['compatible_licenses']:errors.append(e['id']+': license expression requires GPL compatibility review')
  if e.get('shipped') and (not e.get('evidence') or not e.get('source_access')):errors.append(e['id']+': missing license or source evidence')
  for name,expected in e.get('evidence',{}).items():
   p=root/name
   if not p.is_file() or digest(p)!=expected:errors.append('Missing/changed license evidence: '+name)
  if e.get('patterns') and snapshot(root,e['patterns'])!=e.get('files',{}):errors.append('Changed vendored source: '+e['id'])
 # License files copied to the execution host must match the tracked originals.
 for p in (root/'plugin/vizcode/execution-assets/licenses').rglob('*'):
  if p.is_file():
   original=root/'plugin/vizcode/licenses'/p.relative_to(root/'plugin/vizcode/execution-assets/licenses')
   if not original.is_file() or digest(original)!=digest(p):errors.append('Stale/untracked runtime notice: '+str(p.relative_to(root)))
 return errors

def validate_archive(root,archive):
 errors=[];plugin=root/'plugin/vizcode'
 try:
  with zipfile.ZipFile(archive) as z:
   expected=[plugin/p for p in ['LICENSE','COPYRIGHT.md','THIRD_PARTY_NOTICES.md','thirdpartylibs.xml']]
   expected += [p for folder in ['licenses','assets'] for p in (plugin/folder).rglob('*') if p.is_file()]
   for p in expected:
    name='vizcode/'+p.relative_to(plugin).as_posix()
    try:
     if z.read(name)!=p.read_bytes():errors.append('Stale installer evidence/asset: '+name)
    except (KeyError,FileNotFoundError):errors.append('Missing installer evidence/asset: '+name)
 except (OSError,zipfile.BadZipFile):errors.append('Missing/invalid plugin installer: '+str(archive))
 return errors

def main():
 parser=argparse.ArgumentParser();parser.add_argument('action',choices=['refresh','check']);parser.add_argument('--archive',type=Path);parser.add_argument('--details',action='store_true');args=parser.parse_args()
 if not (ROOT/PRIVATE/'licensing/inventory.json').is_file():
  parser.exit(1,'Maintainer release-review configuration is unavailable. Development builds without --zip remain available.\n')
 if args.action=='refresh':refresh(ROOT);return
 inventory=json.loads((ROOT/PRIVATE/'licensing/inventory.json').read_text());errors=validate(ROOT,inventory)
 if args.archive:errors+=validate_archive(ROOT,args.archive)
 if errors:
  print('Distribution packaging did not pass maintainer release verification.',file=sys.stderr)
  if args.details:
   for e in errors:print(' - '+e,file=sys.stderr)
  print('Development builds without --zip remain available.',file=sys.stderr);sys.exit(1)
 print('Dependency license evidence and distribution coverage verified.')
if __name__=='__main__':main()
